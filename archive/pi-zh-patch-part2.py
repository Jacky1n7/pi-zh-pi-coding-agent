def patch(path, reps, label):
    if not path.exists():
        print(f"SKIP (missing): {path}")
        return
    text = path.read_text(encoding="utf-8")
    hit = miss = 0
    for old, new in reps:
        if old in text:
            text = text.replace(old, new)
            hit += 1
        else:
            miss += 1
    path.write_text(text, encoding="utf-8")
    print(f"{label}: hit={hit} miss={miss}")

